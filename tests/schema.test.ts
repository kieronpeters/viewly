// @vitest-environment node
/**
 * Schema-level tests for the library tables (T11).
 *
 * These tests exercise the real generated migration, not a hand-written copy
 * of the schema: they apply `src/db/migrations` to a throwaway SQLite file with
 * the same Drizzle migrator the `db:migrate` CLI uses, then assert the
 * constraints and cascade that the repositories rely on.
 *
 * The database file lives in a fresh `mkdtemp` directory and is deleted after
 * each test, so `data/viewly.db` and any other developer database are never
 * touched.
 *
 * `server-only` does not need mocking here: the schema module and the migrator
 * are plain server code, and this test deliberately opens its own connection
 * instead of importing `src/lib/db/client.ts` (whose module-level cache is
 * process-wide and would leak state between tests).
 */
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

/** Absolute path of the migration folder generated by `npm run db:generate`. */
const MIGRATIONS_FOLDER = fileURLToPath(new URL("../src/db/migrations", import.meta.url));

/** Tables created by the initial migration, excluding Drizzle's journal. */
const LIBRARY_TABLES = [
  "favourites",
  "history",
  "playlist_items",
  "playlists",
  "watch_later",
] as const;

let directory: string;
let sqlite: Database.Database;

beforeEach(() => {
  directory = mkdtempSync(join(tmpdir(), "viewly-schema-"));
  sqlite = new Database(join(directory, "schema-test.db"));

  // Mirror the pragmas from `src/lib/db/client.ts`. `foreign_keys` is what
  // makes the cascade assertion meaningful; SQLite ignores REFERENCES without
  // it.
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");

  migrate(drizzle(sqlite), { migrationsFolder: MIGRATIONS_FOLDER });
});

afterEach(() => {
  if (sqlite.open) {
    sqlite.close();
  }

  rmSync(directory, { recursive: true, force: true, maxRetries: 3 });
});

/** Inserts a favourite row with only the values that matter to the test. */
function insertFavourite(videoId: string): void {
  sqlite
    .prepare(
      `insert into favourites
         (video_id, title, channel_title, thumbnail_url, duration_seconds, saved_at)
       values (?, ?, ?, ?, ?, ?)`,
    )
    .run(videoId, "Title", "Channel", "https://example.com/t.jpg", 42, 1_700_000_000_000);
}

/** Inserts a playlist row. */
function insertPlaylist(id: string): void {
  sqlite
    .prepare(
      `insert into playlists (id, name, created_at, updated_at)
       values (?, ?, ?, ?)`,
    )
    .run(id, "My playlist", 1_700_000_000_000, 1_700_000_000_000);
}

/** Inserts a playlist item row. */
function insertPlaylistItem(playlistId: string, videoId: string, position: number): void {
  sqlite
    .prepare(
      `insert into playlist_items (playlist_id, video_id, position, added_at)
       values (?, ?, ?, ?)`,
    )
    .run(playlistId, videoId, position, 1_700_000_000_000);
}

/** Returns every user table (and index) name in the temp database. */
function schemaObjects(type: "table" | "index"): string[] {
  return (
    sqlite
      .prepare(
        `select name from sqlite_master
         where type = ? and name not like 'sqlite_%'
         order by name`,
      )
      .all(type) as Array<{ name: string }>
  ).map((row) => row.name);
}

describe("library schema migration", () => {
  it("creates all five library tables", () => {
    const tables = schemaObjects("table");

    expect(tables).toEqual(expect.arrayContaining([...LIBRARY_TABLES]));
    expect(tables).toContain("__drizzle_migrations");
  });

  it("creates the indexes the library lists order by", () => {
    expect(schemaObjects("index")).toEqual(
      expect.arrayContaining([
        "favourites_saved_at_idx",
        "history_last_viewed_at_idx",
        "playlist_items_playlist_id_position_idx",
        "watch_later_saved_at_idx",
      ]),
    );
  });

  it("rejects a duplicate favourite", () => {
    insertFavourite("video-a");

    expect(() => insertFavourite("video-a")).toThrow(
      /UNIQUE constraint failed: favourites\.video_id/,
    );
    expect(
      (sqlite.prepare("select count(*) as count from favourites").get() as { count: number }).count,
    ).toBe(1);
  });

  it("rejects a duplicate video in the same playlist", () => {
    insertPlaylist("playlist-1");
    insertPlaylistItem("playlist-1", "video-a", 0);

    expect(() => insertPlaylistItem("playlist-1", "video-a", 1)).toThrow(
      /UNIQUE constraint failed: playlist_items\.playlist_id, playlist_items\.video_id/,
    );
  });

  it("allows the same video in two different playlists", () => {
    insertPlaylist("playlist-1");
    insertPlaylist("playlist-2");
    insertPlaylistItem("playlist-1", "video-a", 0);

    expect(() => insertPlaylistItem("playlist-2", "video-a", 0)).not.toThrow();
  });

  it("deletes a playlist's items when the playlist is deleted", () => {
    insertPlaylist("playlist-1");
    insertPlaylistItem("playlist-1", "video-a", 0);
    insertPlaylistItem("playlist-1", "video-b", 1);

    sqlite.prepare("delete from playlists where id = ?").run("playlist-1");

    expect(
      (
        sqlite
          .prepare("select count(*) as count from playlist_items where playlist_id = ?")
          .get("playlist-1") as { count: number }
      ).count,
    ).toBe(0);
  });

  it("rejects a negative view count and a negative playlist position", () => {
    expect(() =>
      sqlite
        .prepare(
          `insert into history
             (video_id, title, channel_title, thumbnail_url, last_viewed_at, view_count)
           values (?, ?, ?, ?, ?, ?)`,
        )
        .run("video-a", "Title", "Channel", "https://example.com/t.jpg", 1, -1),
    ).toThrow(/CHECK constraint failed: history_view_count_non_negative/);

    insertPlaylist("playlist-1");

    expect(() => insertPlaylistItem("playlist-1", "video-a", -1)).toThrow(
      /CHECK constraint failed: playlist_items_position_non_negative/,
    );
  });

  it("is a no-op when applied a second time", () => {
    insertFavourite("video-a");

    // The migrator records each migration in `__drizzle_migrations`; a second
    // run must skip it rather than re-running the (non-idempotent) CREATEs.
    expect(() => migrate(drizzle(sqlite), { migrationsFolder: MIGRATIONS_FOLDER })).not.toThrow();

    expect(
      (
        sqlite.prepare("select count(*) as count from __drizzle_migrations").get() as {
          count: number;
        }
      ).count,
    ).toBe(1);

    // Existing data survived, so the schema was not recreated.
    expect(
      (sqlite.prepare("select count(*) as count from favourites").get() as { count: number }).count,
    ).toBe(1);
  });
});
