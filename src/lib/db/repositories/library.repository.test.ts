// @vitest-environment node
/**
 * Tests for the library query layer (T12).
 *
 * Every test opens a throwaway SQLite file in a fresh `mkdtemp` directory,
 * applies the real migrations from `src/db/migrations` with the same Drizzle
 * migrator that `npm run db:migrate` uses, and hands that client to
 * `createLibraryRepository`. `data/viewly.db` is never opened, and the sandbox
 * is deleted after each test (the handle is closed first because Windows will
 * not delete an open file).
 *
 * The repository imports `server-only`, which throws outside a Server Component
 * graph; Vitest is not one, so the package is mocked.
 */
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import * as schema from "@/db/schema";
import {
  createLibraryRepository,
  type LibraryRepository,
  type VideoSnapshot,
} from "@/lib/db/repositories/library.repository";

vi.mock("server-only", () => ({}));

/** Absolute path of the migration folder generated by `npm run db:generate`. */
const MIGRATIONS_FOLDER = fileURLToPath(new URL("../../../../src/db/migrations", import.meta.url));

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

let directory: string;
let sqlite: Database.Database;
let repository: LibraryRepository;

/** A complete display snapshot for a fake video. */
function snapshot(videoId: string, overrides: Partial<VideoSnapshot> = {}): VideoSnapshot {
  return {
    videoId,
    title: `Title ${videoId}`,
    channelTitle: "Channel",
    thumbnailUrl: "https://example.com/thumbnail.jpg",
    durationSeconds: 42,
    ...overrides,
  };
}

/** Shorthand for the UTC-millisecond timestamp columns. */
function at(milliseconds: number): Date {
  return new Date(milliseconds);
}

beforeEach(() => {
  directory = mkdtempSync(join(tmpdir(), "viewly-library-"));
  sqlite = new Database(join(directory, "library-test.db"));

  // Mirror the pragmas from `src/lib/db/client.ts`. `foreign_keys` is what
  // makes the playlist cascade assertion meaningful.
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");

  const db = drizzle(sqlite, { schema });

  migrate(db, { migrationsFolder: MIGRATIONS_FOLDER });

  repository = createLibraryRepository(db);
});

afterEach(() => {
  if (sqlite.open) {
    sqlite.close();
  }

  rmSync(directory, { recursive: true, force: true, maxRetries: 3 });
});

describe("favourites", () => {
  it("saves videos and lists them newest first", () => {
    repository.favourites.add({ ...snapshot("video-a"), savedAt: at(1_000) });
    repository.favourites.add({ ...snapshot("video-b"), savedAt: at(2_000) });

    expect(repository.favourites.list().map((row) => row.videoId)).toEqual(["video-b", "video-a"]);
    expect(repository.favourites.isFavourite("video-a")).toBe(true);
    expect(repository.favourites.isFavourite("video-c")).toBe(false);
  });

  it("treats a duplicate save as a no-op and keeps the original snapshot", () => {
    const first = repository.favourites.add({
      ...snapshot("video-a", { title: "Original title" }),
      savedAt: at(1_000),
    });

    const duplicate = repository.favourites.add({
      ...snapshot("video-a", { title: "Later title" }),
      savedAt: at(2_000),
    });

    // The duplicate returns the stored row, not the rejected input.
    expect(duplicate).toEqual(first);
    expect(duplicate.savedAt).toEqual(at(1_000));
    expect(duplicate.title).toBe("Original title");

    const rows = repository.favourites.list();

    expect(rows).toHaveLength(1);
    expect(rows[0]?.videoId).toBe("video-a");
  });

  it("removes idempotently", () => {
    repository.favourites.add({ ...snapshot("video-a"), savedAt: at(1_000) });

    expect(repository.favourites.remove("video-a")).toBe(true);
    expect(repository.favourites.remove("video-a")).toBe(false);
    expect(repository.favourites.list()).toEqual([]);
  });
});

describe("watch later", () => {
  it("adds, lists newest first and removes idempotently", () => {
    repository.watchLater.add({ ...snapshot("video-a"), savedAt: at(1_000) });
    repository.watchLater.add({ ...snapshot("video-b"), savedAt: at(2_000) });

    expect(repository.watchLater.list().map((row) => row.videoId)).toEqual(["video-b", "video-a"]);
    expect(repository.watchLater.isInWatchLater("video-b")).toBe(true);
    expect(repository.watchLater.isInWatchLater("video-c")).toBe(false);

    expect(repository.watchLater.remove("video-b")).toBe(true);
    expect(repository.watchLater.remove("video-b")).toBe(false);
    expect(repository.watchLater.list().map((row) => row.videoId)).toEqual(["video-a"]);
  });

  it("treats a duplicate queue entry as a no-op", () => {
    const first = repository.watchLater.add({ ...snapshot("video-a"), savedAt: at(1_000) });
    const duplicate = repository.watchLater.add({ ...snapshot("video-a"), savedAt: at(2_000) });

    expect(duplicate).toEqual(first);
    expect(repository.watchLater.list()).toHaveLength(1);
  });
});

describe("history", () => {
  it("records a first view, then increments the count and moves the timestamp", () => {
    const first = repository.history.recordView({ ...snapshot("video-a"), viewedAt: at(1_000) });

    expect(first.viewCount).toBe(1);
    expect(first.lastViewedAt).toEqual(at(1_000));

    const second = repository.history.recordView({
      ...snapshot("video-a", { title: "Refreshed title" }),
      viewedAt: at(2_000),
    });

    // One row per video, with the counter bumped and the snapshot refreshed.
    expect(second.videoId).toBe("video-a");
    expect(second.viewCount).toBe(2);
    expect(second.lastViewedAt).toEqual(at(2_000));
    expect(second.title).toBe("Refreshed title");

    const rows = repository.history.list();

    expect(rows).toHaveLength(1);
    expect(rows[0]?.viewCount).toBe(2);
  });

  it("lists most recently viewed first", () => {
    repository.history.recordView({ ...snapshot("video-a"), viewedAt: at(1_000) });
    repository.history.recordView({ ...snapshot("video-b"), viewedAt: at(2_000) });

    expect(repository.history.list().map((row) => row.videoId)).toEqual(["video-b", "video-a"]);
  });

  it("clears one entry idempotently and clears all entries", () => {
    repository.history.recordView({ ...snapshot("video-a"), viewedAt: at(1_000) });
    repository.history.recordView({ ...snapshot("video-b"), viewedAt: at(2_000) });

    expect(repository.history.clearOne("video-a")).toBe(true);
    expect(repository.history.clearOne("video-a")).toBe(false);
    expect(repository.history.list().map((row) => row.videoId)).toEqual(["video-b"]);

    expect(repository.history.clearAll()).toBe(1);
    expect(repository.history.list()).toEqual([]);
    expect(repository.history.clearAll()).toBe(0);
  });
});

describe("playlists", () => {
  it("creates with a caller-supplied id and generates one when omitted", () => {
    const created = repository.playlists.create({
      id: "playlist-fixed",
      name: "Road trips",
      createdAt: at(1_000),
      updatedAt: at(1_000),
    });

    expect(created.id).toBe("playlist-fixed");
    expect(created.name).toBe("Road trips");

    const generated = repository.playlists.create({
      name: "Later",
      createdAt: at(2_000),
      updatedAt: at(2_000),
    });

    expect(generated.id).toMatch(UUID_PATTERN);
    expect(generated.id).not.toBe("playlist-fixed");
  });

  it("renames and records the caller's updatedAt", () => {
    repository.playlists.create({
      id: "playlist-1",
      name: "Old name",
      createdAt: at(1_000),
      updatedAt: at(1_000),
    });

    const renamed = repository.playlists.rename("playlist-1", "New name", at(3_000));

    expect(renamed?.name).toBe("New name");
    expect(renamed?.createdAt).toEqual(at(1_000));
    expect(renamed?.updatedAt).toEqual(at(3_000));
    expect(repository.playlists.rename("missing", "Nope", at(4_000))).toBeUndefined();
  });

  it("lists playlists with item counts, most recently modified first", () => {
    repository.playlists.create({
      id: "playlist-old",
      name: "Old",
      createdAt: at(1_000),
      updatedAt: at(1_000),
    });
    repository.playlists.create({
      id: "playlist-new",
      name: "New",
      createdAt: at(2_000),
      updatedAt: at(3_000),
    });

    repository.playlistItems.add({
      playlistId: "playlist-new",
      videoId: "video-a",
      addedAt: at(4_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-new",
      videoId: "video-b",
      addedAt: at(5_000),
    });

    const rows = repository.playlists.list();

    expect(rows.map((row) => row.id)).toEqual(["playlist-new", "playlist-old"]);
    expect(rows.map((row) => row.itemCount)).toEqual([2, 0]);
  });

  it("deletes a playlist and cascades to its items", () => {
    repository.playlists.create({
      id: "playlist-1",
      name: "Doomed",
      createdAt: at(1_000),
      updatedAt: at(1_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(2_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-b",
      addedAt: at(3_000),
    });

    expect(repository.playlists.delete("playlist-1")).toBe(true);

    // The cascade is enforced by the schema's foreign key, not by the
    // repository deleting items itself.
    expect(
      (
        sqlite
          .prepare("select count(*) as count from playlist_items where playlist_id = ?")
          .get("playlist-1") as { count: number }
      ).count,
    ).toBe(0);
    expect(repository.playlists.get("playlist-1")).toBeUndefined();
    expect(repository.playlists.delete("playlist-1")).toBe(false);
  });

  it("returns a playlist with its items ordered by position", () => {
    repository.playlists.create({
      id: "playlist-1",
      name: "Ordered",
      createdAt: at(1_000),
      updatedAt: at(1_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(2_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-b",
      addedAt: at(3_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-c",
      addedAt: at(4_000),
    });

    const playlist = repository.playlists.get("playlist-1");

    expect(playlist?.id).toBe("playlist-1");
    expect(playlist?.name).toBe("Ordered");
    expect(playlist?.items.map((item) => item.videoId)).toEqual(["video-a", "video-b", "video-c"]);
    expect(playlist?.items.map((item) => item.position)).toEqual([0, 1, 2]);
  });
});

describe("playlist items", () => {
  beforeEach(() => {
    repository.playlists.create({
      id: "playlist-1",
      name: "Queue",
      createdAt: at(1_000),
      updatedAt: at(1_000),
    });
  });

  it("appends positions in insertion order", () => {
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(2_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-b",
      addedAt: at(3_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-c",
      addedAt: at(4_000),
    });

    const items = repository.playlistItems.list("playlist-1");

    expect(items.map((item) => item.videoId)).toEqual(["video-a", "video-b", "video-c"]);
    expect(items.map((item) => item.position)).toEqual([0, 1, 2]);
  });

  it("treats a duplicate add as a no-op and keeps the original position", () => {
    const first = repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(2_000),
    });

    const duplicate = repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(3_000),
    });

    expect(duplicate).toEqual(first);
    expect(duplicate.position).toBe(0);
    expect(duplicate.addedAt).toEqual(at(2_000));
    expect(repository.playlistItems.list("playlist-1")).toHaveLength(1);
  });

  it("leaves a gap when an item is removed, and the next add still appends", () => {
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(2_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-b",
      addedAt: at(3_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-c",
      addedAt: at(4_000),
    });

    expect(repository.playlistItems.remove("playlist-1", "video-b")).toBe(true);
    expect(repository.playlistItems.remove("playlist-1", "video-b")).toBe(false);

    const appended = repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-d",
      addedAt: at(5_000),
    });

    // Positions are append-only, not compacted: removing video-b leaves a hole
    // at 1 and the new item still goes after the highest position.
    expect(appended.position).toBe(3);

    const items = repository.playlistItems.list("playlist-1");

    expect(items.map((item) => item.videoId)).toEqual(["video-a", "video-c", "video-d"]);
    expect(items.map((item) => item.position)).toEqual([0, 2, 3]);
  });

  it("keeps the same video in different playlists independent", () => {
    repository.playlists.create({
      id: "playlist-2",
      name: "Second",
      createdAt: at(2_000),
      updatedAt: at(2_000),
    });

    repository.playlistItems.add({
      playlistId: "playlist-1",
      videoId: "video-a",
      addedAt: at(3_000),
    });
    repository.playlistItems.add({
      playlistId: "playlist-2",
      videoId: "video-a",
      addedAt: at(4_000),
    });

    expect(repository.playlistItems.list("playlist-1").map((item) => item.videoId)).toEqual([
      "video-a",
    ]);
    expect(repository.playlistItems.list("playlist-2").map((item) => item.videoId)).toEqual([
      "video-a",
    ]);
  });

  it("throws when the playlist does not exist, because of the foreign key", () => {
    expect(() =>
      repository.playlistItems.add({
        playlistId: "missing",
        videoId: "video-a",
        addedAt: at(2_000),
      }),
    ).toThrow(/FOREIGN KEY constraint failed/);
  });
});
